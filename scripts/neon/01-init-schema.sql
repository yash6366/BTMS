-- ============================================================================
-- BHEL TRANSPORT MANAGEMENT SYSTEM - NEON POSTGRESQL SCHEMA INITIALIZATION
-- ============================================================================
-- Audited objects:
-- 1. axusers (Authentication & Permissions)
-- 2. cabbooking1_new (Core Ride Bookings)
-- 3. CABBOOKING_DETAILS (Transport Dispatch Processing Table)
-- 4. APPROVAL_NOTIFICATIONS (Manager Notification Queue)
-- 5. EDN_PIS_EMPLOYEE_MASTER_VIEW (Employee Master Information)
-- ============================================================================

-- 1. axusers Table
CREATE TABLE IF NOT EXISTS "axusers" (
    "username" VARCHAR(50) PRIMARY KEY,
    "password" VARCHAR(255),
    "pwd" VARCHAR(50),
    "hashed_password" BYTEA,
    "password_hash" VARCHAR(255), -- Stores modern bcrypt hash
    "usergroup" VARCHAR(50),
    "groupno" VARCHAR(10),
    "build" VARCHAR(1) DEFAULT '0',
    "manage" VARCHAR(1) DEFAULT '0',
    "tools" VARCHAR(1) DEFAULT '0',
    "email" VARCHAR(100),
    "pageaccess" VARCHAR(255),
    "active" VARCHAR(1) DEFAULT '1',
    "Reportingto" VARCHAR(50),
    "created_at" TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    "updated_at" TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. cabbooking1_new Table
CREATE TABLE IF NOT EXISTS "cabbooking1_new" (
