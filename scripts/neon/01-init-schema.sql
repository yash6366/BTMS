    "PASSENGER_NAME" VARCHAR(50),
    "MOB_NO_USER" VARCHAR(13),
    "INDENTER_NAME" VARCHAR(60),
    "MOB_NO_INDTR" VARCHAR(13),
    "STAFF_NO" VARCHAR(7),
    "STAFF_NO_INDTR" VARCHAR(7),
    "STAFF_NO_USER" VARCHAR(7),
    "DEPT_USER" VARCHAR(50),
    "OTHER_DETAILS" VARCHAR(100),
    "INTERNAL_NO" VARCHAR(12),
    "STARTING_PLACE" VARCHAR(75),
    "FLIGHT_TRAIN_NO" VARCHAR(15),
    "TAKE_OFF_FROM" VARCHAR(30),
    "DESTINATION" VARCHAR(75),
    "TRIP_TIME" VARCHAR(6),
    "TRIP_DATE" TIMESTAMP WITH TIME ZONE,
    "INDENT_DATE" TIMESTAMP WITH TIME ZONE,
    "VEH_REQUESTED" VARCHAR(50),
    "DURATION_REQ" VARCHAR(7),
    "PURPOSE" VARCHAR(60),
    "STAFF_NO_APVR" VARCHAR(7),
    "STATUS_APVR" VARCHAR(10) DEFAULT 'OPEN',
    "STATUS_USER" VARCHAR(10) DEFAULT 'CLSD',
    "SERIAL_NO" VARCHAR(11),
    "PASS_DATE_APVR" TIMESTAMP WITH TIME ZONE,
    "VEH_ALLOTTED" VARCHAR(100),
    "VEHICLE_NO" VARCHAR(50),
    "DRIVER_NAME" VARCHAR(100),
    "DRIVER_MOB_NO" VARCHAR(15),
    "REMARKS_USER" TEXT,
    "REMARKS_APVR" TEXT,
    "REMARKS_TRANS" TEXT,
    "STATUS_TRANS" VARCHAR(10),
    "COMPANY_NAME" VARCHAR(100),
    "CREATED_DATE" TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    "UPDATED_DATE" TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. CABBOOKING_DETAILS Table (Physical transport-dispatch table)
CREATE TABLE IF NOT EXISTS "CABBOOKING_DETAILS" (
    "SERIAL_NO" VARCHAR(10) PRIMARY KEY,
    "STAFF_NO_INDTR" VARCHAR(7),
    "STAFF_NO_USER" VARCHAR(7),
    "PASSENGER_NAME" VARCHAR(50),
    "MOB_NO_INDTR" VARCHAR(13),
    "MOB_NO_USER" VARCHAR(13),
    "STARTING_PLACE" VARCHAR(75),
    "FLIGHT_TRAIN_NO" VARCHAR(15),
    "TAKE_OFF_FROM" VARCHAR(30),
    "DESTINATION" VARCHAR(75),
    "TRIP_HR" VARCHAR(2),
    "TRIP_MIN" VARCHAR(2),
    "TRIP_TIME" VARCHAR(6),
    "TRIP_DATE" TIMESTAMP WITH TIME ZONE,
    "INDENT_TIME" VARCHAR(10),
    "INDENT_DATE" TIMESTAMP WITH TIME ZONE,
    "VEH_REQUESTED" VARCHAR(50),
    "DURATION_REQ" VARCHAR(7),
    "PURPOSE" VARCHAR(60),
    "REMARKS_USER" VARCHAR(80),
    "STAFF_NO_APVR" VARCHAR(7),
    "STATUS_USER" VARCHAR(4),
    "PASS_DATE_APVR" TIMESTAMP WITH TIME ZONE,
    "REMARKS_APVR" VARCHAR(80),
    "STATUS_APVR" VARCHAR(4),
    "COMPANY_NAME" VARCHAR(100),
    "OTHER_DETAILS" VARCHAR(100),
    "DEPT_USER" VARCHAR(50),
    "START_PLACE_TYPE" VARCHAR(2),
    "DEPT_INDT" VARCHAR(5),
    "INDENTER_NAME" VARCHAR(60),
    "INTERNAL_NO" VARCHAR(12),
    "STATUS_TRANS" VARCHAR(20) DEFAULT 'PEND',
    "VEH_ALLOTTED" VARCHAR(100),
    "VEHICLE_NO" VARCHAR(50),
    "DRIVER_NAME" VARCHAR(100),
    "DRIVER_MOB_NO" VARCHAR(15),
    "REMARKS_TRANS" TEXT,
    "CREATED_DATE" TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    "UPDATED_DATE" TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. APPROVAL_NOTIFICATIONS Table
CREATE TABLE IF NOT EXISTS "APPROVAL_NOTIFICATIONS" (
    "ID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SERIAL_NO" VARCHAR(11),
    "APPROVER_STAFF_NO" VARCHAR(7),
    "REQUESTER_NAME" VARCHAR(60),
    "PASSENGER_NAME" VARCHAR(50),
    "TRIP_DATE" TIMESTAMP WITH TIME ZONE,
    "PURPOSE" VARCHAR(60),
    "NOTIFICATION_DATE" TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    "STATUS" VARCHAR(10) DEFAULT 'PENDING',
    "CREATED_DATE" TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    "UPDATED_DATE" TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. EDN_PIS_EMPLOYEE_MASTER_VIEW Table
CREATE TABLE IF NOT EXISTS "EDN_PIS_EMPLOYEE_MASTER_VIEW" (
    "EMP_ID" VARCHAR(10) PRIMARY KEY,
    "EMP_FNAME" VARCHAR(50),
    "EMP_MNAME" VARCHAR(50),
    "EMP_LNAME" VARCHAR(50),
    "EMP_DESIGNATION" VARCHAR(100),
    "EMP_EMAIL_ID" VARCHAR(100),
    "DEPT" VARCHAR(50),
    "ACTIVE" VARCHAR(1) DEFAULT '1'
);

-- 6. ACCESS_REQUESTS Table (Explicit role elevation & onboarding request tracking)
CREATE TABLE IF NOT EXISTS "ACCESS_REQUESTS" (
    "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "username" VARCHAR(50) NOT NULL,
    "requested_role" VARCHAR(50) NOT NULL,
    "status" VARCHAR(20) DEFAULT 'PENDING', -- PENDING, APPROVED, REJECTED
    "reason" TEXT,
    "requested_at" TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    "reviewed_at" TIMESTAMP WITH TIME ZONE,
    "reviewed_by" VARCHAR(50),
    "review_notes" TEXT
);

-- 7. ADMIN_AUDIT_LOGS Table (Append-only structured security audit trail)
CREATE TABLE IF NOT EXISTS "ADMIN_AUDIT_LOGS" (
    "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "action" VARCHAR(100) NOT NULL,
    "target_type" VARCHAR(50),
    "target_id" VARCHAR(50),
    "actor" VARCHAR(50) NOT NULL,
    "details" JSONB,
    "ip_address" VARCHAR(50),
    "created_at" TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS "idx_cabbooking_staff_no_user" ON "cabbooking1_new"("STAFF_NO_USER");
CREATE INDEX IF NOT EXISTS "idx_cabbooking_staff_no_apvr" ON "cabbooking1_new"("STAFF_NO_APVR");
CREATE INDEX IF NOT EXISTS "idx_cabbooking_status_apvr" ON "cabbooking1_new"("STATUS_APVR");
CREATE INDEX IF NOT EXISTS "idx_cabbooking_serial_no" ON "cabbooking1_new"("SERIAL_NO");
CREATE INDEX IF NOT EXISTS "idx_cabbooking_trip_date" ON "cabbooking1_new"("TRIP_DATE");
CREATE INDEX IF NOT EXISTS "idx_notifications_approver_status" ON "APPROVAL_NOTIFICATIONS"("APPROVER_STAFF_NO", "STATUS");
CREATE INDEX IF NOT EXISTS "idx_notifications_serial" ON "APPROVAL_NOTIFICATIONS"("SERIAL_NO");
CREATE INDEX IF NOT EXISTS "idx_details_internal_no" ON "CABBOOKING_DETAILS"("INTERNAL_NO");
CREATE INDEX IF NOT EXISTS "idx_details_status_trans" ON "CABBOOKING_DETAILS"("STATUS_TRANS");
CREATE INDEX IF NOT EXISTS "idx_access_requests_username_status" ON "ACCESS_REQUESTS"("username", "status");
CREATE INDEX IF NOT EXISTS "idx_admin_audit_created_at" ON "ADMIN_AUDIT_LOGS"("created_at" DESC);

